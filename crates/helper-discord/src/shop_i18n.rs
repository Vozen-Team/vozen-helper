#[cfg(test)]
mod tests {
    #[test]
    fn every_discord_locale_has_all_shop_labels() {
        for locale in crate::private_replies::DISCORD_LOCALES {
            assert!(include_str!("shop_i18n.rs").contains(&format!("\"{locale}\" =>")));
            for key in 0..11 {
                assert!(!super::text(locale, key).is_empty());
            }
        }
        assert_ne!(super::text("pt-BR", 0), super::text("en-US", 0));
    }
}
